function parseDistanceMeters(label) {
  if (label.includes("건물 내")) return 0;
  const km = label.match(/([\d.]+)\s*km/);
  if (km) return Math.round(parseFloat(km[1]) * 1000);
  const m = label.match(/([\d.]+)\s*m/);
  return m ? Math.round(parseFloat(m[1])) : 99999;
}

// r(id, 이름, 카테고리, 주소, 전화|null, 거리라벨, 평점|null, 리뷰수|null, 영업시간|null, 메뉴목록)
function r(id, name, category, address, phone, distanceLabel, rating, reviewCount, hours, menuList) {
  const menus = (menuList.length ? menuList : [[null, null]]).map(([mName, mPrice], idx) => {
    const finalName = mName || "대표메뉴 (매장 문의)";
    const finalPrice = mPrice || "가격 매장 문의";
    const { avoidTags, weatherTags } = inferTags(finalName);
    return {
      id: `${id}_${idx + 1}`,
      name: finalName,
      price: finalPrice,
      budget: inferBudget(mPrice),
      avoidTags,
      weatherTags,
      emoji: emojiFor(category, finalName)
    };
  });

  return {
    id, name, category, address, phone,
    distanceLabel, distanceMeters: parseDistanceMeters(distanceLabel),
    rating, reviewCount, hours: hours || "매장 문의",
    mapUrl: naverMapUrl(`${name} 송도`),
    menus
  };
}

